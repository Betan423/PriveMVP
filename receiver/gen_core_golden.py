"""Writes golden TSV files so the Android port (CoreTasksTest) is tested against the Python reference.

python3 -m receiver.gen_core_golden --dataset <source_raw_v5.json>
"""

from __future__ import annotations

import argparse
import itertools
import json
from pathlib import Path

from .core_tasks import RESCUE_FACT_VALUES, SYMPTOM_DETAILS, interpret, rescue_rule, rescue_state_from_environment

OUT = Path(__file__).resolve().parent.parent / "app/src/test/resources"
EXTRA_UTTERANCES = ("不用了，先取消。", "今天天氣如何", "把照片傳給", "手機好像壞掉了", "幫我把照片傳給醫生",
                    "我想傳出遊相簿這張給女兒", "這則訊息可信嗎", "手機聲音好小")
STATE_KEYS = ("airplane_mode", "network", "internet_validated", "transport", "dnd_mode", "ringer_mode", "ring_volume_band")


def q(value: str | None) -> str:
    return "-" if value is None else value


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--dataset", type=Path, required=True)
    args = parser.parse_args()
    data = json.loads(args.dataset.read_text(encoding="utf-8"))
    utterances = sorted({t["utterance"] for t in data["task_requests"]} | set(EXTRA_UTTERANCES))
    states = {tuple(rescue_state_from_environment(e["continuous_state_data"]).items())
              for e in data["phone_environments"]}
    # Plus a deterministic sweep so every branch is exercised, not only the dataset's combinations.
    sweep = itertools.product(("on", "off", "unknown"), ("connected", "offline", "unknown"), ("yes", "no"),
                              ("WIFI", "CELLULAR"), ("on", "off", "unknown"), ("normal", "vibrate", "silent", "unknown"),
                              ("zero", "low", "normal", "unknown"))
    states |= {tuple(zip(STATE_KEYS, combo)) for i, combo in enumerate(sweep) if i % 7 == 0}
    lines = []
    for u in utterances:
        i = interpret(u)
        assert "\t" not in u and "\n" not in u
        lines.append("\t".join(map(q, (u, i.intent, i.relation, i.selection, i.symptom_category, i.symptom_detail,
                                         i.requested_scope))))
    rescue = []
    for state in sorted(states):
        s = dict(state)
        assert all(s[k] in RESCUE_FACT_VALUES[k] for k in STATE_KEYS)
        for category, details in SYMPTOM_DETAILS.items():
            for detail in details:
                for scope in ("guided_help", "inspect_only"):
                    sop, codes = rescue_rule(s, category, detail, scope)
                    rescue.append("\t".join([*(s[k] for k in STATE_KEYS), category, detail, scope, sop, ",".join(codes)]))
    OUT.mkdir(parents=True, exist_ok=True)
    header = "# Generated by `python3 -m receiver.gen_core_golden` from receiver/core_tasks.py. Do not edit by hand.\n"
    (OUT / "core_interpret_golden.tsv").write_text(header + "\n".join(lines) + "\n", encoding="utf-8")
    (OUT / "core_rescue_golden.tsv").write_text(header + "# " + "\t".join(STATE_KEYS) +
                                                 "\tcategory\tdetail\tscope\tsop\tcodes\n" + "\n".join(rescue) + "\n",
                                                 encoding="utf-8")
    print(f"{len(lines)} interpret cases, {len(rescue)} rescue cases -> {OUT}")


if __name__ == "__main__":
    main()
