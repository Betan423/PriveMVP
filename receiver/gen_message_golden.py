"""Regenerates MessageGuardGoldenCases.kt so the Android port is tested against the Python reference.

The case texts are kept as-is (read back from the existing Kotlin file); every expected field is
recomputed from receiver/phone_sim.py. Run after changing redaction, feature extraction or rules:

  python -m receiver.gen_message_golden
"""

from __future__ import annotations

import re
from pathlib import Path

from .assistant import rule_assessment
from .phone_sim import extract_facts, redact

KT_PATH = Path(__file__).resolve().parent.parent / "app/src/test/java/com/example/privagentcollector/MessageGuardGoldenCases.kt"
FLAG_ORDER = ("asks_transfer", "requests_secret", "urgency", "has_link", "offers_reward",
              "requests_remote_control", "context_sufficient")
HEADER = """package com.example.privagentcollector

// Generated by `python -m receiver.gen_message_golden` from receiver/phone_sim.py (python reference).
// Do not edit by hand; regenerate when either implementation changes.
// flags order: asks_transfer, requests_secret, urgency, has_link, offers_reward, requests_remote_control, context_sufficient
internal data class Golden(
    val text: String, val redacted: String, val flags: String, val impersonation: String,
    val linkKind: String, val level: String, val codes: String
)

internal val goldenCases = listOf(
"""


def kt_escape(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$")


def kt_unescape(value: str) -> str:
    return re.sub(r"\\u([0-9a-fA-F]{4})", lambda m: chr(int(m.group(1), 16)),
                  value.replace('\\"', '"').replace("\\$", "$").replace("\\\\", "\\"))


def main() -> None:
    content = KT_PATH.read_text(encoding="utf-8")
    texts = [kt_unescape(raw) for raw in re.findall(r'Golden\("((?:[^"\\]|\\.)*)"', content)]
    if not texts:
        raise SystemExit("no Golden(...) cases found in " + str(KT_PATH))
    lines = []
    for text in texts:
        facts = extract_facts(text, "pasted")
        level, codes = rule_assessment(facts)
        flags = "".join("1" if facts[name] else "0" for name in FLAG_ORDER)
        fields = (text, redact(text), flags, facts["impersonation"], facts["link_kind"], level, ",".join(codes))
        lines.append("        Golden(" + ", ".join('"' + kt_escape(field) + '"' for field in fields) + "),")
    KT_PATH.write_text(HEADER + "\n".join(lines) + "\n)\n", encoding="utf-8")
    print(f"{len(lines)} golden cases -> {KT_PATH}")


if __name__ == "__main__":
    main()
